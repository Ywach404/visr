#!/usr/bin/env python3
"""The menu titles VISR draws over the game's own pictures (port/assets/titles/titles.json, the list
tools/embed_assets.py embeds in the game) as a C table for the host's texture upscaler
(port/runtime/texture_policy.h): the bitmap's tag, index and level-0 checksum. A title's original is never shown while
display.high_res_text is on, so the upscaler leaves it alone.

  embed_title_replacements.py TITLES_JSON OUTPUT_C"""

import json
import sys


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit("usage: embed_title_replacements.py TITLES_JSON OUTPUT_C")
    assets = json.load(open(sys.argv[1]))["assets"]
    lines = ['/* generated by tools/embed_title_replacements.py: do not edit */', '', '#include "texture_policy.h"', '',
             "const struct texture_policy_replacement texture_title_replacements[] =", "{"]
    for asset in assets:
        if not asset["tag"].isascii():
            sys.exit(f"embed_title_replacements: {asset['tag']!r} is not ASCII")
        lines.append(f'\t{{ {json.dumps(asset["tag"])}, {asset["bitmap"]}, 0x{asset["crc"]:08x}u }},')
    if not assets:
        lines.append("\t{ 0 },")
    lines += ["};", f"const size_t texture_title_replacement_count = {len(assets)};", ""]
    open(sys.argv[2], "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
